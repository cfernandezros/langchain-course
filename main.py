from dotenv import load_dotenv
from typing import List
from pydantic import BaseModel, Field
from langchain.agents import create_agent
from langchain_core.messages import HumanMessage
from langchain_openai import ChatOpenAI
from langchain_ollama import ChatOllama
from langchain_tavily import TavilySearch

load_dotenv()


class Source(BaseModel):
    """Schema for a source used by the agent"""

    url: str = Field(description="The URL of the source")


class AgentResponse(BaseModel):
    """Schema for the agent's response with answer and sources"""

    answer: str = Field(description="The answer generated by the agent")
    sources: List[Source] = Field(
        default_factory=list, description="The sources used by the agent"
    )


# llm = ChatOllama(model="qwen3.5:2b", temperature=0)
llm = ChatOpenAI(model_name="gpt-6-luna")
tools = [TavilySearch()]
agent = create_agent(model=llm, tools=tools, response_format=AgentResponse)


def main():
    result = agent.invoke(
        {
            "messages": HumanMessage(
                content="Search for 3 job openings for ai eningeering roles using langchain in Madrid and list their details"
            )
        }
    )
    print(result)


if __name__ == "__main__":
    main()
